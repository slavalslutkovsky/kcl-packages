#!/usr/bin/env bash
# tools/litmus-hub.sh — regenerate packages/app/litmus_hub.k, the Litmus
# ChaosExperiment definitions a `provider: litmus` Fault renders next to its
# ChaosEngine.
#
#   tools/litmus-hub.sh [ref]      (default 3.31.0; `just litmus-hub [ref]`)
#
# A ChaosEngine only names an experiment; the definition (go-runner image,
# command, default env) is a namespaced ChaosExperiment that has to exist in
# the engine's namespace. Upstream publishes those in litmuschaos/chaos-charts,
# one faults/kubernetes/<name>/fault.yaml per experiment. They are copied here
# verbatim (spec.definition + the description) rather than fetched at render
# time: function-kcl renders offline, and a pinned copy is what keeps the
# go-runner image in step with the operator. Keep `ref` equal to the `litmus`
# row's ref in packages/providers/registry.yaml (the chaos-operator version).
#
# Only the experiments the Fault vocabulary maps to (see _litmusExperiments in
# packages/app/lib.k) are copied. Requires: git, yq v4, jq, kcl.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
ref=${1:-3.31.0}
out="$root/packages/app/litmus_hub.k"
experiments=(
    pod-delete container-kill
    pod-network-latency pod-network-loss pod-network-corruption pod-network-duplication
    pod-network-rate-limit pod-network-partition
    pod-cpu-hog pod-memory-hog
    pod-http-latency pod-http-reset-peer
    pod-dns-error
)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
git -c advice.detachedHead=false clone -q --depth 1 --branch "$ref" https://github.com/litmuschaos/chaos-charts.git "$tmp/charts"

# One JSON object {<name>: {description, definition}}, then `kcl import` turns
# it into a KCL literal (JSON true/null are not KCL).
for e in "${experiments[@]}"; do
    yq -o json "{\"$e\": {\"description\": (.description.message | sub(\"\\n\$\"; \"\")), \"definition\": .spec.definition}}" \
        "$tmp/charts/faults/kubernetes/$e/fault.yaml"
done | jq -s 'add' >"$tmp/hub.json"
kcl import -m json "$tmp/hub.json" -o "$tmp/hub.k" --force >/dev/null

{
    cat <<EOF
"""
Litmus ChaosExperiment definitions, copied from litmuschaos/chaos-charts@$ref
(faults/kubernetes/<name>/fault.yaml: description.message + spec.definition).
Generated by tools/litmus-hub.sh — do not edit; re-run it with a new ref.
Imported by lib.k as hub: hub.version, hub.experiments[<name>].
"""
version = "$ref"

EOF
    # `kcl import` emits a docstring then a bare top-level dict; name the dict.
    sed -n '/^{/,$p' "$tmp/hub.k" | sed '1s/^{/experiments = {/'
} >"$out"
kcl fmt "$out" >/dev/null
echo "generated $out (${#experiments[@]} experiments from chaos-charts@$ref)"
